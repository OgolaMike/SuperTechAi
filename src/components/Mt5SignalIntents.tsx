import { useCallback, useEffect, useState } from 'react';
import { RefreshCw } from 'lucide-react';
import { supabase } from '@/lib/supabase';

export type Mt5SignalIntent = {
  id: string;
  symbol: string;
  timeframe: string;
  direction: 'BUY' | 'SELL';
  order_type: 'BUY_STOP' | 'SELL_STOP';
  entry: number | string;
  stop_loss: number | string;
  take_profit: number | string;
  signal_epoch: number;
  strategy_version: string;
  status: string;
  expires_at: string | null;
  created_at: string;
  payload?: { current_price?: number; timeframe_agreement?: number; note?: string } | null;
};

type Props = { onSelect: (intent: Mt5SignalIntent) => void };

export function Mt5SignalIntents({ onSelect }: Props) {
  const [intents, setIntents] = useState<Mt5SignalIntent[]>([]);
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState('');

  const refresh = useCallback(async () => {
    setBusy(true);
    setMessage('');
    try {
      const { data, error } = await supabase.functions.invoke('mt5-bridge', {
        body: { action: 'list_signal_intents' },
      });
      if (error) throw error;
      if (data?.error) throw new Error(data.error);
      setIntents((data?.intents ?? []) as Mt5SignalIntent[]);
      setMessage(data?.intents?.length ? 'Fresh backend proposals loaded. No broker orders have been placed.' : 'No fresh backend proposals are waiting for review.');
    } catch (error) {
      setMessage(error instanceof Error ? error.message : 'Could not load backend proposals.');
    } finally {
      setBusy(false);
    }
  }, []);

  useEffect(() => { void refresh(); }, [refresh]);

  return (
    <section className="rounded-xl border border-line/10 bg-canvas/60 p-4">
      <div className="flex items-center justify-between gap-3">
        <div>
          <h3 className="text-sm font-semibold text-ink">AI pending-order proposals</h3>
          <p className="mt-1 text-xs leading-5 text-ink-2">Generated by the backend scanner from closed candles and eight-timeframe agreement. These are suggestions only.</p>
        </div>
        <button type="button" onClick={() => void refresh()} disabled={busy} aria-label="Refresh backend proposals" className="rounded-lg border border-line/20 p-2 text-ink disabled:opacity-40">
          <RefreshCw className={`h-4 w-4 ${busy ? 'animate-spin' : ''}`} />
        </button>
      </div>
      {message && <p role="status" className="mt-3 text-xs text-ink-2">{message}</p>}
      <div className="mt-3 space-y-2">
        {intents.map((intent) => (
          <article key={intent.id} className="rounded-lg border border-line/10 bg-surface/[0.04] p-3">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <p className="text-sm font-semibold text-ink">{intent.symbol} · {intent.order_type.replace('_', ' ')}</p>
              <span className="rounded-full border border-accent/20 px-2 py-1 text-[10px] font-semibold text-accent">{intent.payload?.timeframe_agreement ?? 8}/8 timeframes</span>
            </div>
            <p className="mt-2 text-xs text-ink-2">Entry {Number(intent.entry)} · Stop loss {Number(intent.stop_loss)} · Take profit {Number(intent.take_profit)}</p>
            <p className="mt-1 text-xs text-ink-2">Signal: {new Date(intent.signal_epoch * 1000).toLocaleString()} · Expires: {intent.expires_at ? new Date(intent.expires_at).toLocaleString() : 'Not specified'}</p>
            <p className="mt-1 text-xs text-ink-2">Eight timeframe agreement. Confirm current price and broker symbol before proceeding.</p>
            <button type="button" onClick={() => onSelect(intent)} className="mt-3 rounded-lg bg-accent px-3 py-2 text-xs font-semibold text-white">Review in broker check</button>
          </article>
        ))}
      </div>
    </section>
  );
}
